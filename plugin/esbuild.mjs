#!/usr/bin/env node
/**
 * Build script.
 *
 * Two very different outputs:
 *
 *  1. `dist/blockbench-ai-agent.js` — the Blockbench plugin. Blockbench runs plugin
 *     code through `new Function('requireNativeModule', 'require', code)`
 *     (js/plugin_loader.ts), so the bundle MUST be a self contained IIFE with no
 *     runtime imports and no `require` calls. `platform: 'browser'` plus a single
 *     bundled entry guarantees that.
 *
 *  2. `dist/agent-bridge.js` — the Node bridge. ESM for Node 20+, with `ws` and
 *     `pngjs` left external so they resolve from node_modules normally.
 */

import { build, context } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const watch = process.argv.includes('--watch');
const dev = watch || process.argv.includes('--dev');

const pluginBanner = `/**
 * Blockbench AI Agent — plugin bundle.
 * Generated by esbuild; do not edit. Source: src/plugin/**
 */`;

/** @type {import('esbuild').BuildOptions} */
const pluginOptions = {
  entryPoints: [path.join(HERE, 'src/plugin/index.ts')],
  outfile: path.join(HERE, 'dist/blockbench-ai-agent.js'),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome110'],
  globalName: undefined,
  sourcemap: dev ? 'inline' : false,
  minify: !dev,
  keepNames: true,
  legalComments: 'none',
  banner: { js: pluginBanner },
  logLevel: 'info',
  define: { 'process.env.NODE_ENV': JSON.stringify(dev ? 'development' : 'production') },
};

/** @type {import('esbuild').BuildOptions} */
const bridgeOptions = {
  entryPoints: [path.join(HERE, 'src/bridge/index.ts')],
  outfile: path.join(HERE, 'dist/agent-bridge.js'),
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: ['node20'],
  sourcemap: dev ? 'inline' : false,
  minify: false,
  external: ['ws', 'pngjs'],
  banner: { js: '#!/usr/bin/env node' },
  logLevel: 'info',
};

function exists(file) {
  try {
    return fs.existsSync(file);
  } catch {
    return false;
  }
}

async function run() {
  fs.mkdirSync(path.join(HERE, 'dist'), { recursive: true });
  const targets = [pluginOptions];
  if (exists(path.join(HERE, 'src/bridge/index.ts'))) targets.push(bridgeOptions);
  else console.warn('• src/bridge/index.ts not found yet; building the plugin bundle only');

  if (watch) {
    const contexts = await Promise.all(targets.map((options) => context(options)));
    await Promise.all(contexts.map((ctx) => ctx.watch()));
    console.log('watching for changes…');
    return;
  }
  for (const options of targets) {
    await build(options);
  }
  console.log('build complete');
}

run().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
